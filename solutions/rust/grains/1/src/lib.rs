pub fn square(s: u32) -> u64 {
    // 1. 边界检查：棋盘格子是 1 到 64
    if s < 1 || s > 64 {
        panic!("Square must be between 1 and 64");
    }

    // 2. 计算第 s 个格子的麦粒
    // 第 1 格: 2^0 = 1
    // 第 2 格: 2^1 = 2
    // 第 s 格: 2^(s-1)
    // 使用位移运算 1 << (s-1) 效率极高，等同于 2 的幂
    1u64 << (s - 1)
}

pub fn total() -> u64 {
    // 整个棋盘的总数是 2^64 - 1
    // 但在 u64 中直接计算 2^64 会导致溢出（u64 最大值是 2^64 - 1）
    // 我们可以直接利用 u64::MAX 的特性，它在二进制上就是 64 个 1
    u64::MAX
}
